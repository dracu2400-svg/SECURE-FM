def check_firmware_update():
    """Check for firmware updates"""
    print("\n=== Checking for Firmware Updates ===")

    response = requests.get(f"{SERVER_URL}/firmware/latest")

    if response.status_code == 200:
        firmware = response.json()
        print(f"Latest firmware: {firmware['version']}")
        print(f"  Size: {firmware['size']} bytes")
        print(f"  SHA256: {firmware['sha256']}")
        print(f"  Security Counter: {firmware['security_counter']}")
    elif response.status_code == 404:
        print("No firmware available")
    else:
        print(f"✗ Failed to check firmware: {response.text}")

def main():
    """Main entry point"""
    print("=" * 60)
    print(" TF-M Device Client Example")
    print("=" * 60)

    try:
        # Generate keys
        private_key, public_key_pem = generate_device_keys()

        # Copy public key to server certificates directory for verification
        print("\n⚠ IMPORTANT: Copy device_public_key.pem to server's certificates/ directory")
        print("   cp device_public_key.pem ../certificates/test-tracker-001.pem")
        input("\nPress ENTER after copying the key...")

        # Register device
        if not register_device(public_key_pem):
            print("\n✗ Failed to register device")
            return

        # Perform attestation
        if not perform_attestation(private_key):
            print("\n✗ Attestation failed")
            return

        # Submit telemetry
        submit_telemetry()

        # Check for updates
        check_firmware_update()

        print("\n" + "=" * 60)
        print("✓ Example completed successfully!")
        print("=" * 60)

    except requests.exceptions.ConnectionError:
        print("\n✗ Error: Could not connect to server")
        print("   Make sure the server is running: python tfm_cloud_server.py")
    except Exception as e:
        print(f"\n✗ Error: {e}")
        import traceback
        traceback.print_exc()

if __name__ == '__main__':
    main()
